import streamlit as st
import random

# ตั้งค่าหน้าตาเว็บเบื้องต้น
st.set_page_config(page_title="เกมทายคำศัพท์", page_icon="🎮")

st.title("🎮 ยินดีต้อนรับสู่เกมทายคำศัพท์!")
st.write("-------------------------------------------")

# รายชื่อคำศัพท์ 10 คำของคุณ
vocab = [
    ["cucumber", "แตงกวา"],
    ["Lion", "สิงโต"],
    ["Snake", "งู"],
    ["Vegetable", "ผัก"],
    ["River", "แม่น้ำ"],
    ["Iron", "เหล็ก"],
    ["Headphone", "หูฟัง"],
    ["Bottle", "ขวด"],
    ["Nail", "เล็บ"],
    ["Rice", "ข้าว"]
]

# สร้างระบบเก็บสถานะของเกมบนหน้าเว็บ (Session State)
if "started" not in st.session_state:
    st.session_state.started = False
if "current_question" not in st.session_state:
    st.session_state.current_question = 1
if "score" not in st.session_state:
    st.session_state.score = 0
if "current_word" not in st.session_state:
    st.session_state.current_word = random.choice(vocab)
if "game_over" not in st.session_state:
    st.session_state.game_over = False

# หน้าแรก: ถามว่าพร้อมเล่นไหม
if not st.session_state.started:
    st.subheader("พร้อมจะลุยกันหรือยัง?")
    col1, col2 = st.columns(2)

    with col1:
        if st.button("กด 1: ลุยเลย! 🚀"):
            st.session_state.started = True
            st.rerun()

    with col2:
        if st.button("กด 0: ไม่เล่น ออกเกม 👋"):
            st.warning("กำลังออกจากเกม... ไว้ว่างๆ มาเล่นกันใหม่นะ!")

# หน้าเล่นเกม
elif st.session_state.started and not st.session_state.game_over:
    st.subheader(f"ข้อที่ {st.session_state.current_question}/10")

    english_word = st.session_state.current_word[0]
    thai_word = st.session_state.current_word[1]

    st.markdown(f"### คำว่า **'{english_word}'** แปลว่าอะไร?")

    user_answer = st.text_input("พิมพ์คำตอบของคุณที่นี่:", key=f"q_{st.session_state.current_question}")

    if st.button("ส่งคำตอบ 🎯"):
        if user_answer.strip() == thai_word:
            st.success("ถูกต้อง! เก่งมาก! 🎉")
            st.session_state.score += 1
        else:
            st.error(f"ผิดดด! คำตอบที่ถูกต้องคือ '{thai_word}' 😅")

        # ตรวจสอบว่าครบ 10 ข้อหรือยัง
        if st.session_state.current_question < 10:
            st.session_state.current_question += 1
            st.session_state.current_word = random.choice(vocab)
            # พักแป๊บนึงให้เห็นคำตอบก่อนกดข้อต่อไป
            st.button("ไปข้อถัดไป ➡️")
        else:
            st.session_state.game_over = True
            st.rerun()

# หน้าจบเกม แสดงคะแนน
else:
    st.balloons() # ยิงพลุฉลองจบเกม!
    st.write("-------------------------------------------")
    st.header(f"🏁 จบเกมแล้ว! คุณได้คะแนนทั้งหมด {st.session_state.score}/10 คะแนน")

    # ระบบตัดเกรดสไตล์ครู COMMANDER.YUT
    if st.session_state.score == 10:
        st.success("เพอร์เฟกต์! เอาเกรด A+ ไปครองเลยนักเรียน! 🏆")
    elif st.session_state.score >= 5:
        st.info("สอบผ่าน! เก่งใช้ได้เลยนะเรา 👍")
    else:
        st.warning("โดนตีแน่! ไปท่องศัพท์มาเพิ่มด่วนๆ เลย! 📖")

    if st.button("เล่นใหม่อีกครั้ง 🔄"):
        st.session_state.started = False
        st.session_state.current_question = 1
        st.session_state.score = 0
        st.session_state.game_over = False
        st.rerun()

